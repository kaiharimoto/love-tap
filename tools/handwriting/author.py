# where the cedilla hangs (bottom centre of the c bowl)
CEDILLA_X = {"c": 210, "C": 330}


def compose(name, cp, base_name, accent_name):
    base = GLYPHS.get(base_name) or PARTS[base_name]
    acc = PARTS[accent_name]
    upper = base_name[0].isupper()
    if accent_name == "cedilla":
        dx, dy = CEDILLA_X[base_name], 0
    else:
        dx = base["accent_x"]
        dy = 240 if upper else 0
        if upper and accent_name == "dieresis":
            dy += 20

    def shifted():
        return [[[x + dx, y + dy, p] for x, y, p in s] for s in acc["strokes"]]

    def roles_of(src):
        r = list(src.get("roles") or [None] * len(src["strokes"]))
        return r + list(acc.get("roles") or [None] * len(acc["strokes"]))

    entry = {"cp": cp, "strokes": [list(map(list, s)) for s in base["strokes"]] + shifted(),
             "roles": roles_of(base), "composed": [base_name, accent_name]}
    if base.get("alts"):
        entry["alts"] = []
        for alt in base["alts"]:
            a = {"name": alt["name"], "strokes": [list(map(list, s)) for s in alt["strokes"]] + shifted(),
                 "roles": roles_of(alt)}
            if alt.get("tags"):
                a["tags"] = alt["tags"]
            entry["alts"].append(a)
    GLYPHS[name] = entry


def main():
    for name, (cp, base, acc) in COMPOSED.items():
        compose(name, cp, base, acc)
    data = {
        "metrics": {"upm": 1000, "xheight": 480, "cap": 720, "ascender": 760, "descender": -220},
        "point_format": "[x, y, pressure]; strokes are centripetal Catmull-Rom paths",
        "glyphs": GLYPHS,
        "parts": PARTS,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, separators=(",", ":"), sort_keys=True)
    n_alts = sum(len(g.get("alts", [])) for g in GLYPHS.values())
    print(f"wrote {OUT}: {len(GLYPHS)} glyphs, {n_alts} alternates")


if __name__ == "__main__":
    main()
