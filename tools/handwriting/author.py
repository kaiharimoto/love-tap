"""tools/handwriting/author.py — the authored stroke skeletons, written out as skeletons.json.

Coordinates: 1000-unit em, baseline 0, x-height 480, cap 720, ascender 760, descender -220.
A glyph is a list of strokes; a stroke is "x y p, x y p, ..." (p = pen pressure 0-100) and is
rendered as a centripetal Catmull-Rom path through those points. Reversals sharper than the
corner threshold in build.py become pen corners (the hand retracing a stem).

The letterforms are a quick adult print-script: entry ticks, exit strokes, retraced stems,
open counters; "alts" carry structurally different ways of writing the same letter.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "skeletons.json")

GLYPHS = {}
PARTS = {}


def P(s):
    """'x y p, x y p | x y p, ...' -> list of strokes of [x, y, pressure]."""
    strokes = []
    for stroke in s.split("|"):
        pts = []
        for tok in stroke.strip().split(","):
            tok = tok.strip()
            if not tok:
                continue
            x, y, p = tok.split()
            pts.append([float(x), float(y), float(p) / 100.0])
        if pts:
            strokes.append(pts)
    return strokes


def G(name, cp, strokes, alts=None, roles=None, accent_x=None, **extra):
    entry = {"cp": cp, "strokes": P(strokes)}
    if roles:
        entry["roles"] = roles
    if alts:
        entry["alts"] = []
        for a in alts:
            alt = {"name": a[0], "strokes": P(a[1])}
            if len(a) > 2 and a[2]:
                alt["roles"] = a[2]
            if len(a) > 3 and a[3]:
                alt["tags"] = a[3]
            entry["alts"].append(alt)
    if accent_x is not None:
        entry["accent_x"] = accent_x
    entry.update(extra)
    GLYPHS[name] = entry


def PART(name, strokes, **extra):
    PARTS[name] = {"strokes": P(strokes), **extra}


